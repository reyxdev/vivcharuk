// Emits dist/theme.css: a Tailwind CSS v4 `@theme inline` block mapping tokens to
// Tailwind namespaces. Colours and fluid sizes reference the vars from tokens.css
// (so [data-theme="dark"] switches them at runtime); static values are written literally.
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  breakpoint,
  color,
  container,
  cubicBezier,
  ease,
  fontFamily,
  light,
  measure,
  radius,
  sectionY,
  shadow,
  space,
  typeScale,
  type EaseName,
} from '../src/index';

const kebab = (s: string): string => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const rem = (px: number): string => `${px / 16}rem`;

const lines: string[] = [];
const decl = (name: string, value: string | number): void => {
  lines.push(`  --${name}: ${value};`);
};
const section = (title: string): void => {
  lines.push('', `  /* ${title} */`);
};

section('colour: semantic layer only, plus decorative meadow (round 11)');
decl('color-*', 'initial');
for (const name of Object.keys(light)) decl(`color-${name}`, `var(--${name})`);
for (const name of Object.keys(color)) if (name.startsWith('meadow-')) decl(`color-${name}`, `var(--c-${name})`);

section('font families (docs/10 §10.2); sans/serif re-pointed so Tailwind defaults use them');
decl('font-sans', fontFamily.body);
decl('font-serif', fontFamily.quote);
for (const [k, v] of Object.entries(fontFamily)) decl(`font-${k}`, v);

section('type scale (docs/10 §10.3)');
decl('text-*', 'initial');
for (const [k, s] of Object.entries(typeScale)) {
  const sizes: [string, string][] = [[k, `var(--type-${k}-size)`]];
  if (s.fluid === null && s.desktop !== s.mobile) sizes.push([`${k}-desktop`, `var(--type-${k}-size-desktop)`]);
  for (const [name, size] of sizes) {
    decl(`text-${name}`, size);
    decl(`text-${name}--line-height`, s.lineHeight);
    decl(`text-${name}--letter-spacing`, s.tracking);
    decl(`text-${name}--font-weight`, s.weight);
  }
}

section('spacing: 4 px step (docs/11 §11.1) — p-4 = space-4 = 16 px; plus fluid section padding');
decl('spacing', space[1]);
for (const k of Object.keys(sectionY)) decl(`spacing-section-y-${k}`, `var(--section-y-${k})`);

section('breakpoints (docs/11 §11.3)');
decl('breakpoint-*', 'initial');
for (const [k, v] of Object.entries(breakpoint)) decl(`breakpoint-${k}`, rem(v));

section('containers (docs/11 §11.3) and measure (docs/10 §10.4) for max-w-*');
for (const [k, v] of Object.entries(container)) if (k !== 'full') decl(`container-${k}`, v);
for (const [k, v] of Object.entries(measure)) decl(`container-measure-${k}`, v);

section('radius (docs/11 §11.5); rounded-none and rounded-full are Tailwind statics');
decl('radius-*', 'initial');
for (const [k, v] of Object.entries(radius)) if (k !== 'none' && k !== 'full') decl(`radius-${k}`, v);

section('elevation (docs/11 §11.5)');
decl('shadow-*', 'initial');
for (const [k, v] of Object.entries(shadow)) decl(`shadow-${k}`, v);

section('easing (docs/13 §13.3); ease-linear is a Tailwind static');
decl('ease-*', 'initial');
for (const k of Object.keys(ease)) if (k !== 'linear') decl(`ease-${kebab(k)}`, cubicBezier(k as EaseName));
decl('default-transition-timing-function', cubicBezier('gentle'));

const css = [
  '/* Generated by packages/tokens/build/emit-tailwind.ts. Do not edit. */',
  '/* Import after tokens.css, which defines the runtime vars referenced below. */',
  '@theme inline {',
  ...lines.slice(1),
  '}',
  '',
].join('\n');

const out = new URL('../dist/', import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL('theme.css', out), css);
console.log(`theme.css: ${lines.filter((l) => l.startsWith('  --')).length} theme vars`);
