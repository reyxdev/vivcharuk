// Emits dist/tokens.css: every token as a CSS custom property.
// :root = primitives + light semantics; [data-theme="dark"] = dark semantics.
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  breakpoint,
  color,
  container,
  cubicBezier,
  dark,
  duration,
  ease,
  fontFamily,
  fontWeight,
  grid,
  light,
  measure,
  motionDuration,
  radius,
  sectionY,
  shadow,
  space,
  stagger,
  target,
  thread,
  typeScale,
  zIndex,
  type EaseName,
} from '../src/index';

type Decl = [name: string, value: string | number];

const kebab = (s: string): string => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const ms = (n: number): string => `${n}ms`;
const block = (selector: string, decls: Decl[], indent = ''): string =>
  `${indent}${selector} {\n${decls.map(([k, v]) => `${indent}  --${k}: ${v};`).join('\n')}\n${indent}}\n`;

const gridDecls = (g: (typeof grid)[keyof typeof grid]): Decl[] => [
  ['grid-columns', g.columns],
  ['grid-gutter', `${g.gutter}px`],
  ['grid-margin', g.margin === null ? 'auto' : `${g.margin}px`],
  ['grid-max', g.maxContent === null ? 'none' : `${g.maxContent}px`],
];

const root: Decl[] = [
  ...Object.entries(color).map(([k, v]): Decl => [`c-${k}`, v]),
  ...Object.entries(space).map(([k, v]): Decl => [`space-${k}`, v]),
  ...Object.entries(sectionY).map(([k, v]): Decl => [`section-y-${k}`, v]),
  ...Object.entries(container).map(([k, v]): Decl => [`container-${k}`, v]),
  ...Object.entries(target).map(([k, v]): Decl => [`target-${k}`, v]),
  ...gridDecls(grid.xs),
  ...Object.entries(fontFamily).map(([k, v]): Decl => [`font-${k}`, v]),
  ...Object.entries(fontWeight).map(([k, v]): Decl => [`weight-${k}`, v]),
  ...Object.entries(typeScale).flatMap(([k, s]): Decl[] => [
    [`type-${k}-size`, s.fluid ?? s.mobile],
    ...(s.fluid === null && s.desktop !== s.mobile ? [[`type-${k}-size-desktop`, s.desktop] as Decl] : []),
    [`type-${k}-leading`, s.lineHeight],
    [`type-${k}-tracking`, s.tracking],
    [`type-${k}-weight`, s.weight],
    [`type-${k}-family`, `var(--font-${s.family})`],
  ]),
  ...Object.entries(measure).map(([k, v]): Decl => [`measure-${k}`, v]),
  ...Object.entries(radius).map(([k, v]): Decl => [`radius-${k}`, v]),
  ...Object.entries(shadow).map(([k, v]): Decl => [`shadow-${k}`, v]),
  ...Object.entries(zIndex).map(([k, v]): Decl => [`z-${k}`, v]),
  ...Object.entries(duration).map(([k, v]): Decl => [`dur-${k}`, ms(v)]),
  ...Object.keys(ease).map((k): Decl => [`ease-${kebab(k)}`, cubicBezier(k as EaseName)]),
  ['stagger-menu', ms(stagger.menu)],
  ['stagger-content', ms(stagger.content)],
  ...Object.entries(motionDuration).map(([k, v]): Decl => [`motion-${kebab(k)}`, ms(v)]),
  ...Object.entries(thread).map(([k, v]): Decl => [`thread-${kebab(k)}`, v]),
  ...Object.entries(light).map(([k, v]): Decl => [k, `var(--c-${v})`]),
];

const media = (Object.keys(grid) as (keyof typeof grid)[])
  .filter((bp) => bp !== 'xs')
  .map((bp) => `@media (min-width: ${breakpoint[bp]}px) {\n${block(':root', gridDecls(grid[bp]), '  ')}}\n`);

const darkBlock = block(
  '[data-theme="dark"]',
  Object.entries(dark).map(([k, v]): Decl => [k, `var(--c-${v})`]),
);

const css = [
  '/* Generated by packages/tokens/build/emit-css.ts. Do not edit. */\n',
  block(':root', root),
  ...media,
  darkBlock,
].join('\n');

const out = new URL('../dist/', import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL('tokens.css', out), css);
console.log(`tokens.css: ${root.length} :root vars, ${Object.keys(dark).length} dark overrides`);
